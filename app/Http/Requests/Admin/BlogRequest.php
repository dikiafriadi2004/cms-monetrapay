<?php

namespace App\Http\Requests\Admin;

use Illuminate\Contracts\Validation\ValidationRule;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

class BlogRequest extends FormRequest
{
    /**
     * Determine if the user is authorized to make this request.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * Prepare the data for validation.
     */
    protected function prepareForValidation(): void
    {
        if ($this->has('tags') && is_string($this->tags)) {
            $tags = array_filter(
                array_map('trim', explode(',', $this->tags))
            );
            $this->merge(['tags' => ! empty($tags) ? $tags : null]);
        }
    }

    /**
     * Get the validation rules that apply to the request.
     *
     * @return array<string, ValidationRule|array<mixed>|string>
     */
    public function rules(): array
    {
        $blogId = $this->route('blog')?->id ?? null;

        $rules = [
            'title' => ['required', 'string', 'max:200'],
            'content' => ['required', 'string', 'max:100000'],
            'categories' => ['required', 'array', 'min:1', 'max:5'],
            'categories.*' => ['integer', 'exists:categories,id'],
            'tags' => ['nullable', 'array', 'max:10'],
            'tags.*' => ['string', 'max:50'],
            'featured_image' => ['nullable', 'image', 'max:2048', 'mimes:jpg,jpeg,png,webp'],
            'status' => ['required', 'in:draft,published'],
            'scheduled_at' => ['nullable', 'date', 'after:now'],
            'excerpt' => ['nullable', 'string', 'max:500'],
            'meta_title' => ['nullable', 'string', 'max:60'],
            'meta_description' => ['nullable', 'string', 'max:160'],
            'meta_keywords' => ['nullable', 'string', 'max:500'],
        ];

        // On update, validate slug uniqueness excluding current blog
        if ($blogId) {
            $rules['slug'] = [
                'nullable',
                'string',
                'max:220',
                'regex:/^[a-z0-9]+(?:-[a-z0-9]+)*$/',
                Rule::unique('blogs', 'slug')->ignore($blogId)->withoutTrashed(),
            ];
        } else {
            // On store, slug is auto-generated by SlugService, but allow optional override
            $rules['slug'] = [
                'nullable',
                'string',
                'max:220',
                'regex:/^[a-z0-9]+(?:-[a-z0-9]+)*$/',
            ];
        }

        // Allow removing featured image on update
        if ($blogId) {
            $rules['remove_featured_image'] = ['nullable', 'boolean'];
        }

        return $rules;
    }

    /**
     * Get custom validation messages.
     *
     * @return array<string, string>
     */
    public function messages(): array
    {
        return [
            'title.required' => 'Judul wajib diisi.',
            'title.max' => 'Judul maksimal 200 karakter.',
            'slug.max' => 'Slug maksimal 220 karakter.',
            'slug.regex' => 'Slug hanya boleh berisi huruf kecil, angka, dan tanda hubung.',
            'slug.unique' => 'Slug sudah digunakan oleh artikel lain.',
            'content.required' => 'Konten wajib diisi.',
            'content.max' => 'Konten maksimal 100.000 karakter.',
            'categories.required' => 'Kategori wajib dipilih.',
            'categories.min' => 'Minimal 1 kategori harus dipilih.',
            'categories.max' => 'Maksimal 5 kategori yang dapat dipilih.',
            'categories.*.exists' => 'Kategori yang dipilih tidak valid.',
            'tags.max' => 'Maksimal 10 tags per artikel.',
            'tags.*.max' => 'Setiap tag maksimal 50 karakter.',
            'featured_image.image' => 'Featured image harus berupa file gambar.',
            'featured_image.max' => 'Featured image maksimal 2MB.',
            'featured_image.mimes' => 'Featured image harus berformat JPG, PNG, atau WebP.',
            'status.required' => 'Status wajib dipilih.',
            'status.in' => 'Status harus draft atau published.',
            'scheduled_at.date' => 'Format tanggal jadwal tidak valid.',
            'scheduled_at.after' => 'Tanggal jadwal harus di masa depan.',
            'meta_title.max' => 'Meta title maksimal 60 karakter.',
            'meta_description.max' => 'Meta description maksimal 160 karakter.',
            'meta_keywords.max' => 'Meta keywords maksimal 500 karakter.',
        ];
    }
}
