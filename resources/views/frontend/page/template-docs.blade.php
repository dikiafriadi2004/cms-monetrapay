<script>
// Auto-generate TOC from h2/h3 in content
document.addEventListener('DOMContentLoaded', function() {
    const content = document.getElementById('docs-content');
    const toc     = document.getElementById('toc-nav');
    if (!content || !toc) return;

    const headings = content.querySelectorAll('h2, h3');
    if (!headings.length) { toc.innerHTML = '<p class="text-xs text-slate-400 italic">Tidak ada daftar isi.</p>'; return; }

    toc.innerHTML = '';
    headings.forEach((h, i) => {
        if (!h.id) h.id = 'heading-' + i;
        const a = document.createElement('a');
        a.href = '#' + h.id;
        a.textContent = h.textContent;
        a.className = (h.tagName === 'H2')
            ? 'block py-1 px-2 rounded hover:bg-slate-50 hover:text-primary transition-colors font-medium text-slate-700 text-xs'
            : 'block py-1 px-4 rounded hover:bg-slate-50 hover:text-primary transition-colors text-slate-500 text-xs';
        toc.appendChild(a);
    });
});
</script>
